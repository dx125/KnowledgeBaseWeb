import { defineConfig, devices } from '@playwright/test';

// End-to-end tests in a real browser against a production build in mock mode (MSW in a
// Service Worker, synthetic fixtures, no backend). `npm run e2e` builds it into dist-e2e/
// (never dist/, so a mock build can't be deployed by accident) and serves it with
// `vite preview`. First run on a new machine: `npx playwright install chromium`.
const PORT = 5174;

export default defineConfig({
  testDir: './e2e',
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : 'list',
  use: {
    baseURL: `http://localhost:${PORT}`,
    trace: 'retain-on-failure',
  },
  projects: [
    { name: 'chromium', use: { ...devices['Desktop Chrome'] } },
    { name: 'mobile', use: { ...devices['Pixel 7'] } },
  ],
  webServer: {
    command: `npx vite build --mode mock --outDir dist-e2e --emptyOutDir && npx vite preview --outDir dist-e2e --port ${PORT} --strictPort`,
    url: `http://localhost:${PORT}`,
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
});
